package proxy

import (
	"bytes"
	"crypto/x509"
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"strings"
)

// AuthVerdict describes whether an upstream error or HTTP response indicates session/credential loss.
type AuthVerdict struct {
	RequiresAuth bool
	Reason       string
	Category     string // e.g., "exec-plugin", "tls-cert", "http-401", "teleport-403", "rbac-403"
}

type k8sStatusBody struct {
	APIVersion string `json:"apiVersion"`
	Kind       string `json:"kind"`
	Status     string `json:"status"`
	Message    string `json:"message"`
	Reason     string `json:"reason"`
	Code       int    `json:"code"`
}

// ClassifyTransportError inspects RoundTripper / client-go ExecProvider / TLS handshake errors.
// It distinguishes credential expiry, missing Teleport login, and mTLS client-cert rejection from
// normal network outages or server certificate issues.
func ClassifyTransportError(err error) AuthVerdict {
	if err == nil {
		return AuthVerdict{}
	}

	var certInvalid x509.CertificateInvalidError
	if errors.As(err, &certInvalid) && certInvalid.Reason == x509.Expired {
		// Note: x509.CertificateInvalidError during verify is typically server cert,
		// unless surfaced from client cert parsing. Check message context below too.
	}

	msg := err.Error()
	lower := strings.ToLower(msg)

	// 1. client-go ExecProvider (`tsh kube credentials`) failures.
	// Note: If the Teleport proxy itself is unreachable (`dial tcp ...`, `no such host`, `i/o timeout`),
	// `tsh kube credentials` also exits with code 1, so we MUST check network reachability markers first
	// before classifying an exec failure as auth loss!
	networkFailureMarkers := []string{
		"connect: connection refused",
		"no such host",
		"network is unreachable",
		"no route to host",
		"i/o timeout",
		"context deadline exceeded",
		"tls: handshake timeout",
	}
	for _, nm := range networkFailureMarkers {
		if strings.Contains(lower, nm) {
			return AuthVerdict{}
		}
	}

	execMarkers := []string{
		"no ssh auth methods loaded",
		"are you logged in",
		"relogin required",
		"active profile expired",
		"session has expired",
		"not logged in",
		"please login",
		"tsh login",
		"expired session",
		"credentials have expired",
		"interactivemode",
		"certificate has expired",
		"key has expired",
		"getting credentials: exec:",
		"exec: executable tsh failed",
	}
	for _, m := range execMarkers {
		if strings.Contains(lower, strings.ToLower(m)) {
			return AuthVerdict{
				RequiresAuth: true,
				Reason:       "Teleport session credentials expired or missing",
				Category:     "exec-plugin",
			}
		}
	}

	// 2. TLS alert from mTLS-terminating Teleport proxy rejecting expired/revoked client certificate
	tlsAuthAlerts := []string{
		"remote error: tls: bad certificate",
		"remote error: tls: certificate expired",
		"remote error: tls: certificate revoked",
		"remote error: tls: certificate required",
		"remote error: tls: unknown certificate authority",
		"tls: expired certificate",
	}
	for _, alert := range tlsAuthAlerts {
		if strings.Contains(lower, alert) {
			return AuthVerdict{
				RequiresAuth: true,
				Reason:       "Upstream rejected client TLS certificate",
				Category:     "tls-cert",
			}
		}
	}

	return AuthVerdict{}
}

// ClassifyHTTPResponse inspects an upstream HTTP response without consuming its body permanently.
// Crucially:
//   - HTTP 401 is always an authentication failure.
//   - HTTP 403 from Kubernetes RBAC (`kind: Status`, `reason: Forbidden`, e.g. `User "..." cannot list resource ...`)
//     is NOT an authentication failure and MUST NOT trigger a login modal.
//   - HTTP 403 generated by Teleport Proxy on session revocation, lock enforcement, expired cert, or lost cluster access
//     IS classified as requiring re-authentication.
func ClassifyHTTPResponse(resp *http.Response, isTeleportContext bool) AuthVerdict {
	if resp == nil {
		return AuthVerdict{}
	}

	if resp.StatusCode == http.StatusUnauthorized {
		return AuthVerdict{
			RequiresAuth: true,
			Reason:       "Upstream returned HTTP 401 Unauthorized",
			Category:     "http-401",
		}
	}

	if resp.StatusCode != http.StatusForbidden {
		return AuthVerdict{}
	}

	// Inspect bounded body snippet (max 32 KiB) and restore resp.Body intact.
	const maxInspect = 32 * 1024
	if resp.Body == nil {
		return AuthVerdict{}
	}
	snippet, readErr := io.ReadAll(io.LimitReader(resp.Body, maxInspect))
	if readErr != nil {
		resp.Body = io.NopCloser(bytes.NewReader(snippet))
		return AuthVerdict{}
	}
	resp.Body = &restoredReadCloser{
		Reader: io.MultiReader(bytes.NewReader(snippet), resp.Body),
		Closer: resp.Body,
	}

	return classify403Payload(snippet, resp.Header.Get("Content-Type"), isTeleportContext)
}

func classify403Payload(body []byte, contentType string, isTeleportContext bool) AuthVerdict {
	trimmed := bytes.TrimSpace(body)
	lowerBody := strings.ToLower(string(trimmed))

	// Explicit Teleport revocation / lock / session expiry markers (JSON or plain text)
	teleportRevocationMarkers := []string{
		"session has expired",
		"session expired",
		"certificate has expired",
		"relogin",
		"please login",
		"tsh login",
		"lock targeting",
		"user is locked",
		"session is locked",
		"active lock",
		"revoked",
		"missing certificate",
		"client certificate",
		"expired credentials",
	}
	for _, marker := range teleportRevocationMarkers {
		if strings.Contains(lowerBody, marker) {
			return AuthVerdict{
				RequiresAuth: true,
				Reason:       "Teleport session expired, locked, or revoked (HTTP 403)",
				Category:     "teleport-403-revoked",
			}
		}
	}

	var statusObj k8sStatusBody
	if len(trimmed) > 0 && json.Unmarshal(trimmed, &statusObj) == nil && statusObj.Kind == "Status" {
		msgLower := strings.ToLower(statusObj.Message)

		// Standard Kubernetes RBAC denial shape:
		// e.g. `pods is forbidden: User "user" cannot list resource "pods" in API group "" ...`
		if strings.Contains(msgLower, "cannot ") && strings.Contains(msgLower, "resource") {
			return AuthVerdict{
				RequiresAuth: false,
				Category:     "rbac-403",
			}
		}
		if statusObj.Reason == "Forbidden" && !isTeleportAuthRejectionMessage(msgLower) {
			return AuthVerdict{
				RequiresAuth: false,
				Category:     "rbac-403",
			}
		}
		if isTeleportContext && isTeleportAuthRejectionMessage(msgLower) {
			return AuthVerdict{
				RequiresAuth: true,
				Reason:       "Teleport rejected cluster access: " + scrubMessageSummary(statusObj.Reason),
				Category:     "teleport-403-status",
			}
		}
		return AuthVerdict{
			RequiresAuth: false,
			Category:     "k8s-status-403",
		}
	}

	// Non-Kubernetes 403 response (e.g., plain-text `access denied` from Teleport reverse proxy before reaching kube-apiserver)
	if isTeleportContext && (strings.Contains(lowerBody, "access denied") || !strings.Contains(strings.ToLower(contentType), "json")) {
		return AuthVerdict{
			RequiresAuth: true,
			Reason:       "Teleport proxy rejected session (HTTP 403 access denied)",
			Category:     "teleport-proxy-403",
		}
	}

	return AuthVerdict{
		RequiresAuth: false,
		Category:     "other-403",
	}
}

func isTeleportAuthRejectionMessage(msgLower string) bool {
	// Teleport's kube proxy returns Status{Reason: "Forbidden" or "", Message: "access denied"} or
	// "[00] access denied" when the Teleport user certificate / role session is no longer permitted to reach the cluster
	// (distinct from K8s RBAC which always formats `... is forbidden: User "..." cannot <verb> ...`).
	if strings.TrimSpace(msgLower) == "access denied" || strings.Contains(msgLower, "access denied to") {
		return true
	}
	if strings.Contains(msgLower, "teleport") && (strings.Contains(msgLower, "expired") || strings.Contains(msgLower, "denied") || strings.Contains(msgLower, "login")) {
		return true
	}
	return false
}

func scrubMessageSummary(s string) string {
	if s == "" {
		return "AccessDenied"
	}
	if len(s) > 48 {
		return s[:48]
	}
	return s
}

type restoredReadCloser struct {
	io.Reader
	io.Closer
}
